#!/usr/bin/env python3
"""Bake assets/fonts/Robotica.ttf (Robotica by Courtney Novits, free font)
into src/core/panel_font.inc: 4-bit alpha glyphs at the side-panel sizes.
Usage: python3 tools/bake_font.py  (needs Pillow and fontTools)."""
import os
from PIL import ImageFont
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, 'assets', 'fonts', 'Robotica.ttf')
OUT = os.path.join(ROOT, 'src', 'core', 'panel_font.inc')
SIZES = [16, 20, 26, 34, 48, 60]

cmap = TTFont(TTF).getBestCmap()
out = ['/* Generated by tools/bake_font.py from Robotica.ttf',
       ' * (Robotica by Courtney Novits). Do not edit. */', '']
data = []
glyphs = []
fonts = []
for si, size in enumerate(SIZES):
    f = ImageFont.truetype(TTF, size)
    asc, desc = f.getmetrics()
    first = len(glyphs)
    for c in range(32, 127):
        ch = chr(c)
        if c not in cmap:
            glyphs.append((0, 0, 0, 0, 0, -1))
            continue
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch)
        if c == 32 or box[2] <= box[0]:
            glyphs.append((adv, 0, 0, 0, 0, len(data)))
            continue
        m, (ox, oy) = f.getmask2(ch, mode='L')
        w, h = m.size
        off = len(data)
        row = []
        for y in range(h):
            for x in range(0, w, 2):
                a = m.getpixel((x, y)) >> 4
                b = m.getpixel((x + 1, y)) >> 4 if x + 1 < w else 0
                data.append(a | (b << 4))
        glyphs.append((adv, w, h, ox, oy, off))
    fonts.append((size, asc, first))
out.append('static const uint8_t PF_DATA[%d] = {' % len(data))
for i in range(0, len(data), 24):
    out.append('    ' + ','.join(str(v) for v in data[i:i + 24]) + ',')
out.append('};')
out.append('typedef struct { uint8_t adv, w, h; int8_t ox, oy; int32_t off; } PfGlyph;')
out.append('static const PfGlyph PF_GLYPH[%d] = {' % len(glyphs))
for g in glyphs:
    out.append('    {%d,%d,%d,%d,%d,%d},' % g)
out.append('};')
out.append('typedef struct { uint8_t size, ascent; uint16_t first; } PfFont;')
out.append('static const PfFont PF_FONT[%d] = {' % len(fonts))
for f in fonts:
    out.append('    {%d,%d,%d},' % f)
out.append('};')
open(OUT, 'w').write('\n'.join(out) + '\n')
missing = ''.join(chr(c) for c in range(33, 127) if c not in cmap)
print('baked', len(data), 'bytes; missing ASCII:', missing)
